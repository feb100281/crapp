class Command(BaseCommand):
    help = "Первичное наполнение базы: группы, собственник, валюты, банки, счета, команды, статьи ДДС"

    def handle(self, *args, **options):
        with transaction.atomic():
            self.groups()
            owner = self.owner()
            self.currencies()
            banks = self.banks()
            self.accounts(owner, banks)
            self.jobs()
            self.cf_items()
            self.chart()

        # DaData — вне транзакции: сеть может отвалиться, данные уже сохранены
        self.step("DaData: собственник и банки")
        for obj in [owner, *banks.values()]:
            self.dadata(obj)

        self.stdout.write(self.style.SUCCESS("Готово. Пути к папкам укажите в админке → Список команд."))

    # ------------------------------------------------------------------

    def step(self, text):
        self.stdout.write(self.style.HTTP_INFO(f"— {text}"))

    def groups(self):
        self.step("Группы контрагентов")
        for value, _label in CPRole.choices:
            CPGroup.objects.get_or_create(name=value)

    def owner(self):
        self.step("Собственник (Космо)")
        owner, _ = Gr.objects.get_or_create(inn=OWNER_INN, defaults={"name": "КОСМО ООО"})
        return owner

    def currencies(self):
        self.step("Валюты")
        for sid, code, numeric, name, badge in CURRENCIES:
            Fx.objects.update_or_create(
                numeric_code=numeric,
                defaults={"sid": sid, "code": code, "name": name, "badge": badge},
            )

    def banks(self):
        self.step("Банки")
        bank_group = CPGroup.objects.get(name=CPRole.BANK)
        banks = {}
        for inn, name in BANKS.items():
            cp, _ = CP.objects.get_or_create(inn=inn, defaults={"name": name})
            cp.groups.add(bank_group)
            banks[inn] = cp
        return banks

    def accounts(self, owner, banks):
        self.step("Банковские счета")
        fx = {f.numeric_code: f for f in Fx.objects.all()}
        for number, bank_inn, ba_type in ACCOUNTS:
            BankAccount.objects.update_or_create(
                number=number,
                defaults={
                    "gr": owner,
                    "bank": banks[bank_inn],
                    "currency": fx.get(number[5:8]),
                    "ba_type": ba_type,
                },
            )

    def jobs(self):
        self.step("Команды")
        for spec in JOBS:
            spec = dict(spec)
            command = spec.pop("command")
            job, created = Jobs.objects.get_or_create(
                command=command,
                defaults={**spec, "scope": ScopeOfWorks.LOCAL},
            )
            if not created:
                # обновляем описание, но не трогаем param (там пути пользователя)
                job.name = spec["name"]
                job.description = spec["description"]
                job.save(update_fields=["name", "description"])

    def cf_items(self):
        self.step("Статьи ДДС")
        created = 0
        for activity, direction, number, name, subs in CF_ITEMS:
            item, new = CFItem.objects.get_or_create(
                activity=activity,
                direction=direction,
                parent=None,
                number=number,
                defaults={"name": name},
            )
            created += new
            for sub_number, sub_name in subs:
                _, new = CFItem.objects.get_or_create(
                    parent=item,
                    number=sub_number,
                    defaults={
                        "name": sub_name,
                        "activity": activity,
                        "direction": direction,
                    },
                )
                created += new
        self.stdout.write(f"   новых статей: {created}")

        # пояснения — только туда, где описание пустое
        filled = 0
        for code, text in CF_DESCRIPTIONS.items():
            filled += CFItem.objects.filter(code=code).filter(
                models.Q(description__isnull=True) | models.Q(description="")
            ).update(description=text)
        self.stdout.write(f"   пояснений добавлено: {filled}")

    def chart(self):
        from gl.services.chart import seed_chart, sync_bank_accounts

        self.step("План счетов")
        self.stdout.write(f"   новых счетов: {seed_chart()}, банковских субсчетов: {sync_bank_accounts()}")

    def dadata(self, obj):
        try:
            found = update_cp_from_dadata(obj)
            mark = "ок" if found else "не найден"
        except Exception as exc:  # нет ключа, сети, лимит
            mark = f"пропущено ({exc})"
        self.stdout.write(f"   {obj.inn} {obj.name or ''}: {mark}")
